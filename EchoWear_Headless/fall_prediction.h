#define PREFALL_RISK_THRESHOLD   0.65f  // heuristic risk score [0..1] that fires FALL_PREDICTED
#define PREFALL_COOLDOWN_MS      3000   // suppress repeat predictions while a risk period continues

class FallPredictor {
public:
    // Call with whatever rolling IMU magnitude buffer the caller maintains
    // (the .ino currently passes its 20-sample / ~200ms IMU_BUFFER_SIZE
    // window - the same one used for MQG-HRV motion-tier gating).
    float computeRiskHeuristic(const float* ax_buf, const float* ay_buf, const float* az_buf, int length) {
#if ECHOWEAR_TINYML_ENABLED
        return runTinyMLInference(ax_buf, ay_buf, az_buf, length);
#else
        return runHeuristic(ax_buf, ay_buf, az_buf, length);
#endif
    }

    bool shouldFireAlert(float risk_score, unsigned long now_ms) {
        if (risk_score < PREFALL_RISK_THRESHOLD) return false;
        if (now_ms - last_fire_ms_ < PREFALL_COOLDOWN_MS) return false;
        last_fire_ms_ = now_ms;
        return true;
    }

private:
    unsigned long last_fire_ms_ = 0;

    // Interim heuristic: rising jerk (sample-to-sample change in acceleration
    // magnitude) combined with peak deviation from resting 1g. Intentionally
    // simple - NOT a substitute for a trained classifier.
    float runHeuristic(const float* ax_buf, const float* ay_buf, const float* az_buf, int length) {
        if (length < 3) return 0.0f;

        float jerk_sum = 0.0f;
        float mag_prev = sqrtf(ax_buf[0]*ax_buf[0] + ay_buf[0]*ay_buf[0] + az_buf[0]*az_buf[0]);
        float mag_max_dev = 0.0f;

        for (int i = 1; i < length; i++) {
            float mag = sqrtf(ax_buf[i]*ax_buf[i] + ay_buf[i]*ay_buf[i] + az_buf[i]*az_buf[i]);
            jerk_sum += fabsf(mag - mag_prev);
            float dev = fabsf(mag - 1.0f); // deviation from resting 1g
            if (dev > mag_max_dev) mag_max_dev = dev;
            mag_prev = mag;
        }

        float mean_jerk = jerk_sum / (float)(length - 1);

        // Normalized against rough empirical bounds - clamp to [0,1].
        float jerk_score = mean_jerk / 1.2f;
        float dev_score  = mag_max_dev / 1.5f;

        float risk = 0.6f * jerk_score + 0.4f * dev_score;
        if (risk > 1.0f) risk = 1.0f;
        if (risk < 0.0f) risk = 0.0f;
        return risk;
    }

#if ECHOWEAR_TINYML_ENABLED
    float runTinyMLInference(const float* ax_buf, const float* ay_buf, const float* az_buf, int length) {
        // TODO: build an ei::signal_t from the three buffers, call
        // run_classifier(&signal, &result, false), and return the
        // "fall_risk" output label's confidence. Left unimplemented until
        // the model is exported from Edge Impulse.
        return 0.0f;
    }
#endif
};

#endif // ECHOWEAR_FALL_PREDICTION_H_