// ============================================================================
// FALL PREDICTION (pre-impact early warning)
// ----------------------------------------------------------------------------
// STATUS: heuristic placeholder only. No Edge Impulse model has been trained
// or exported yet. This file is structured so that dropping in a generated
// "<project>_inferencing.h" header and flipping ECHOWEAR_TINYML_ENABLED to 1
// is a self-contained swap - the call site in the .ino (fallPredictor.
// computeRiskHeuristic(...)) does not need to change.
//
// The heuristic below is a design estimate, not calibrated against field
// data. It exists to exercise the FALL_PREDICTED alert path end-to-end
// (firmware -> ESP-NOW -> receiver) before a trained classifier exists, not
// to claim predictive accuracy.
// ============================================================================

#define ECHOWEAR_TINYML_ENABLED 0   // set to 1 once an Edge Impulse model is exported

